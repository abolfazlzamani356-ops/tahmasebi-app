def generate_rozen_catalog_items(discount_pct=15.0):
    multiplier = (100.0 - discount_pct) / 100.0
    items = []
    
    parts_meta = [
        ('دوش', 'شیر حمام (دوش)'),
        ('توالت', 'شیر آفتابه (توالت)'),
        ('روشویی', 'شیر روشویی'),
        ('ظرفشویی', 'شیر ظرفشویی سینک'),
    ]

    for model, color, p_dosh, p_tolet, p_rooshooi, p_zarf, p_set in ROZEN_ROWS:
        prices = [p_dosh, p_tolet, p_rooshooi, p_zarf]
        
        # ۴ تکه مجزا
        for i, (part_key, part_title) in enumerate(parts_meta):
            sell_p = prices[i]
            buy_p = int(sell_p * multiplier)
            items.append({
                'name': f"{part_title} مدل {model} {color} رزن",
                'category': 'شیرآلات',
                'brand': 'رزن',
                'buy_price': buy_p,
                'sell_price': sell_p,
                'description': f"{part_title} رزن مدل {model} رنگ {color} - لیست کارخانه ۱۴۰۵/۰۶/۰۶ با تخفیف ۱۵٪ خرید"
            })
            
        # ست کامل ۴ تکه
        set_sell = p_set
        set_buy = int(set_sell * multiplier)
        items.append({
            'name': f"ست ۴ تکه شیرآلات مدل {model} {color} رزن",
            'category': 'شیرآلات',
            'brand': 'رزن',
            'buy_price': set_buy,
            'sell_price': set_sell,
            'description': f"ست کامل ۴ تکه شیرآلات رزن (دوش، توالت، روشویی، ظرفشویی) مدل {model} رنگ {color} - تخفیف ۱۵٪ خرید"
        })

    return items
