def generate_all_milan_items(discount_pct=18.0):
    """
    تولید لیست کامل محصولات میلان برنز با تبدیل قیمت از ریال به تومان
    و اعمال درصد تخفیف خرید مشخص شده (پیش‌فرض ۱۸٪)
    """
    mult = 1.0 - (discount_pct / 100.0)
    items = []

    for name, cat, rial_price, brand, desc in milan_raw_items:
        sell_p = rial_price // 10  # تبدیل ریال به تومان
        buy_p = int(round(sell_p * mult))
        items.append({
            'name': name,
            'category': cat,
            'brand': brand,
            'sell_price': sell_p,
            'buy_price': buy_p,
            'description': f'{desc} - تخفیف خرید {discount_pct}%'
        })

    return items


