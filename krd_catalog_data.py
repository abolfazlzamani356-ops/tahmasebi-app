def generate_all_krd_items(discount_pct=30.0):
    """
    تولید لیست کامل ۱۲۵ قلم کالای کابین روشویی KRD
    با اعمال دقیق درصد تخفیف خرید (پیش‌فرض ۳۰٪) جهت محاسبه قیمت خرید به تومان
    """
    mult = 1.0 - (discount_pct / 100.0)
    items = []

    for row_num, model, cabin_price, mirror_price, mirror_box_price, box_price, full_set_price in krd_cabin_raw_models:
        # ۱. روشویی فول ست (کابین + آینه باکس)
        fs_sell = full_set_price
        fs_buy = int(round(fs_sell * mult))
        items.append({
            'name': f'روشویی فول ست KRD مدل {model} (کابین + آینه باکس)',
            'category': 'روشویی کابینتی',
            'brand': 'KRD',
            'sell_price': fs_sell,
            'buy_price': fs_buy,
            'description': f'KRD CABIN | ست کامل روشویی کابینتی مدل {model} شامل کابین و آینه باکس | تخفیف خرید {discount_pct}%'
        })

        # ۲. کابین تک روشویی
        cb_sell = cabin_price
        cb_buy = int(round(cb_sell * mult))
        items.append({
            'name': f'کابین تک روشویی KRD مدل {model}',
            'category': 'روشویی کابینتی',
            'brand': 'KRD',
            'sell_price': cb_sell,
            'buy_price': cb_buy,
            'description': f'KRD CABIN | کابین تک روشویی مدل {model} بدون آینه و باکس | تخفیف خرید {discount_pct}%'
        })

        # ۳. آینه باکس روشویی (آینه همراه با باکس)
        mb_sell = mirror_box_price
        mb_buy = int(round(mb_sell * mult))
        items.append({
            'name': f'آینه باکس روشویی KRD مدل {model}',
            'category': 'روشویی کابینتی',
            'brand': 'KRD',
            'sell_price': mb_sell,
            'buy_price': mb_buy,
            'description': f'KRD CABIN | آینه باکس روشویی مدل {model} (آینه و باکس متصل) | تخفیف خرید {discount_pct}%'
        })

        # ۴. باکس تک روشویی
        bx_sell = box_price
        bx_buy = int(round(bx_sell * mult))
        items.append({
            'name': f'باکس تک روشویی KRD مدل {model}',
            'category': 'روشویی کابینتی',
            'brand': 'KRD',
            'sell_price': bx_sell,
            'buy_price': bx_buy,
            'description': f'KRD CABIN | باکس تک کناری روشویی مدل {model} | تخفیف خرید {discount_pct}%'
        })

        # ۵. آینه تک روشویی
        mr_sell = mirror_price
        mr_buy = int(round(mr_sell * mult))
        items.append({
            'name': f'آینه تک روشویی KRD مدل {model}',
            'category': 'روشویی کابینتی',
            'brand': 'KRD',
            'sell_price': mr_sell,
            'buy_price': mr_buy,
            'description': f'KRD CABIN | آینه تک روشویی مدل {model} | تخفیف خرید {discount_pct}%'
        })

    return items


